-- นามสกุลลูกค้า (ไม่บังคับ) (2026-11-10)
--
-- เดิมเก็บชื่อเจ้าของเป็นช่องเดียว (customers.name) — หน้าร้านเรียกกันด้วยชื่อ/ชื่อเล่น
-- ลูกค้าส่วนใหญ่ไม่ได้ให้นามสกุล จึง "ไม่" แยกเป็น first_name/last_name แบบบังคับทั้งคู่
-- เพราะจะได้ข้อมูลเพี้ยน (ชื่อเล่นไปอยู่ช่องนามสกุล) และต้องรื้อจุดที่อ่าน name ทั้งระบบ
--
-- แทนที่ด้วย: name = ชื่อ (บังคับ เหมือนเดิม) + last_name = นามสกุล (ไม่บังคับ)
--   - ใบเสร็จ / ฉลากยา / แจ้งเตือน Telegram ยังใช้ name เหมือนเดิม ไม่ต้องแก้
--   - เอกสารคลินิก (ใบรับรอง/ใบยินยอม) เติมชื่อ-นามสกุลเต็มให้ ตรงนี้คือที่นามสกุลมีค่า
--
-- full_name = คอลัมน์ generated ไว้ "ค้นหา" กับ "แสดง" โดยเฉพาะ
--   พิมพ์ "สมชาย" / "ใจดี" / "สมชาย ใจดี" ต้องเจอหมด — ถ้าค้นแยกสองคอลัมน์
--   คำค้นที่มีเว้นวรรคจะไม่ match คอลัมน์ไหนเลย
--
-- รันใน Supabase SQL Editor (รันซ้ำได้ ไม่พังของเดิม)
--
-- ⚠️ หลังรันไฟล์นี้ ให้รัน supabase-migration-merge-duplicates.sql ซ้ำอีกครั้ง
--    (merge_customers() อัปเดตให้ย้าย/เลือกทับ last_name ได้แล้ว ไม่งั้นนามสกุล
--     ของใบที่ถูกรวมจะหายตอนรวมใบซ้ำ)

ALTER TABLE customers ADD COLUMN IF NOT EXISTS last_name TEXT;

-- ไม่ backfill จากชื่อเดิม: ตัดด้วยเว้นวรรคจะพังกับ "คุณอาร์ม" หรือ "สมชาย (บ้านสวน)"
-- ที่ไม่มีนามสกุลอยู่แล้ว ปล่อยว่างไว้ ค่อยเก็บตอนลูกค้ามาครั้งถัดไป

ALTER TABLE customers ADD COLUMN IF NOT EXISTS full_name TEXT
  GENERATED ALWAYS AS (
    CASE
      WHEN last_name IS NULL OR btrim(last_name) = '' THEN name
      ELSE name || ' ' || btrim(last_name)
    END
  ) STORED;
