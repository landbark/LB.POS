-- หมอฉีดเป็นเศษ ml ได้ (0.6 / 1.2 / 2.5) แต่คิดเงินเป็น ml เต็ม ปัดขึ้น ขั้นต่ำ 1 ml
-- ตัวที่คิดเงินยังเป็น visit_items.quantity เหมือนเดิม (ไหลไปหน้าขาย/บิล/ตัดสต็อคได้ตามปกติ)
-- คอลัมน์นี้เก็บ "ฉีดจริง" ไว้ในเวชระเบียนและใบบันทึกการรักษาเท่านั้น
ALTER TABLE visit_items ADD COLUMN IF NOT EXISTS dose_ml NUMERIC(6,2) CHECK (dose_ml > 0);

-- สัตว์ปกติดี ไม่ได้ป่วย — มาฉีดวัคซีน ตรวจสุขภาพ หรือหายจากโรคที่รักษาแล้ว
-- (แยกเป็นคอลัมน์ ไม่ฝากไว้ในข้อความ diagnosis เพื่อให้ดึงรายงานได้ทีหลัง)
ALTER TABLE visits ADD COLUMN IF NOT EXISTS healthy BOOLEAN NOT NULL DEFAULT false;
